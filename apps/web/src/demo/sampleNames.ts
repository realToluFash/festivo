/** A sample crowd's name at `index`, each name once for the first 1,600. */
export function crowdName(index: number): string {
  const first = FIRST[index % FIRST.length] ?? '';
  const last = LAST[(index + 7 * Math.floor(index / FIRST.length)) % LAST.length] ?? '';

  return `${first} ${last}`;
}
