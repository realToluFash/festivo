#!/usr/bin/env node
// A stack for each role that raises pull requests. How to use it: CONTRIBUTING.md.
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderQaEnv, stackConfig } from './qa-env.mjs';

// Developer 1 is the main checkout on the development ports. QA holds +10000 to +30000.
// Only five whole steps fit under 65536, so the rest take half steps: no two development
// ports are 5000 apart.
export const STACKS = {
  dev2: 40000,
  lead: 45000,
  ops: 50000,
  en: 15000,
  es: 25000,
  fr: 35000,
  pt: 55000,
};

export const DEVELOPERS = [2];

export function roleConfig(role) {
  if (!Object.hasOwn(STACKS, role)) {
    throw new Error(`no stack for ${role}: one of ${Object.keys(STACKS)}`);
  }
  return { role, ...stackConfig(`soirely-${role}`, STACKS[role]) };
}

export function devConfig(developer) {
  if (!DEVELOPERS.includes(developer)) {
    throw new Error(`no developer ${developer} to set up: one of ${DEVELOPERS}`);
  }
  return roleConfig(`dev${developer}`);
}

export function renderDevEnv(example, config) {
  return renderQaEnv(example, config.overrides, config.project, [
    '# Generated by scripts/dev-env.mjs. `just dev-env env` writes it again from .env.example.',
    `# The ${config.role} stack: compose project ${config.project}, with ports of its own.`,
  ]);
}

export function roleOf(worktree) {
  const match = /^soirely-([a-z0-9]+)$/.exec(basename(worktree));
  return match && Object.hasOwn(STACKS, match[1]) ? match[1] : null;
}

export function developerOf(worktree) {
  const match = /^dev(\d+)$/.exec(roleOf(worktree) ?? '');
  return match ? Number(match[1]) : null;
}

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');

function git(args, cwd) {
  const result = spawnSync('git', args, { cwd, encoding: 'utf8' });
  if (result.status !== 0) throw new Error(`git ${args.join(' ')}: ${result.stderr.trim()}`);
  return result.stdout.trim();
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`${command} ${args.join(' ')} exited ${result.status}`);
}

function capture(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, encoding: 'utf8' });
  return result.status === 0 ? result.stdout.trim() : null;
}

function step(label) {
  process.stdout.write(`\n▸ ${label}\n`);
}

function mainCheckout() {
  return dirname(resolve(ROOT, git(['rev-parse', '--git-common-dir'], ROOT)));
}

function worktree(config) {
  return join(dirname(mainCheckout()), config.project);
}

function writeEnv(root, config) {
  const rendered = renderDevEnv(readFileSync(join(root, '.env.example'), 'utf8'), config);
  writeFileSync(join(root, '.env'), rendered);
  console.log(`  .env for compose project ${config.project}`);
}

function setup(config) {
  const root = worktree(config);
  const main = mainCheckout();

  step(`The worktree, at ${root}`);
  if (existsSync(join(root, '.git'))) {
    console.log('  already there');
  } else {
    git(['fetch', '--quiet', 'origin'], main);
    // Detached: the developer branches from here, and git refuses a branch checked out elsewhere.
    git(['worktree', 'add', '--detach', root, 'origin/main'], main);
  }
  const settings = join(main, '.claude/settings.local.json');
  if (existsSync(settings) && !existsSync(join(root, '.claude/settings.local.json'))) {
    copyFileSync(settings, join(root, '.claude/settings.local.json'));
  }

  step('The environment');
  writeEnv(root, config);

  run('node', ['scripts/setup.mjs'], root);

  step('The stack');
  run('docker', ['compose', 'up', '-d', '--build'], root);
  // Waits on the lasting services only: --wait fails when a one-shot init container exits 0.
  const services = JSON.parse(
    capture('docker', ['compose', 'config', '--format', 'json'], root) ?? '{}',
  ).services;
  const lasting = Object.entries(services ?? {})
    .filter(([, service]) => service.restart !== 'no')
    .map(([name]) => name);
  run('docker', ['compose', 'up', '-d', '--wait', '--no-recreate', ...lasting], root);

  step('The databases');
  const console_ = ['compose', 'exec', '-T', 'api', 'php', 'bin/console'];
  run('docker', [...console_, 'lexik:jwt:generate-keypair', '--skip-if-exists'], root);
  run('docker', [...console_, 'doctrine:database:create', '--if-not-exists'], root);
  run('docker', [...console_, 'doctrine:migrations:migrate', '-n', '--allow-no-migration'], root);
  run('npm', ['run', 'test:db'], root);

  status(config);
}

function env(config) {
  step('The environment');
  writeEnv(worktree(config), config);
  console.log('  `docker compose up -d` picks it up.');
}

function status(config) {
  const root = worktree(config);
  const branch = capture('git', ['branch', '--show-current'], root) || 'detached';
  const health = capture('curl', [
    '-sf',
    '-o',
    '/dev/null',
    '-w',
    '%{http_code}',
    `${config.urls.api}/api/health`,
  ]);
  console.log(`
${config.role} stack ${config.project} — ${root}
  Branch    ${branch}
  API       ${config.urls.api}   ${health === '200' ? 'answering' : 'NOT answering'}
  Web       ${config.urls.web}
  Mailpit   ${config.urls.mailpit}`);
}

const COMMANDS = { setup, env, status };

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const argv = process.argv.slice(2);
  let role = roleOf(ROOT);
  const developerFlag = argv.indexOf('--developer');
  if (developerFlag !== -1) role = `dev${argv.splice(developerFlag, 2)[1]}`;
  const roleFlag = argv.indexOf('--role');
  if (roleFlag !== -1) role = argv.splice(roleFlag, 2)[1];
  const [name = 'status'] = argv;
  try {
    if (!COMMANDS[name]) throw new Error(`unknown command ${name}: ${Object.keys(COMMANDS)}`);
    if (role === null) throw new Error('which stack? `--developer 2` or `--role lead`');
    COMMANDS[name](roleConfig(role));
  } catch (error) {
    process.stderr.write(`\n✗ ${error instanceof Error ? error.message : String(error)}\n`);
    process.exit(1);
  }
}
