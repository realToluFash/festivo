import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import {
  DEVELOPERS,
  devConfig,
  developerOf,
  renderDevEnv,
  roleConfig,
  roleOf,
  STACKS,
} from './dev-env.mjs';
import { qaConfig, TESTERS } from './qa-env.mjs';

// Two stacks on one port is a developer's tests reading another stack's database.
describe('a second developer’s stack', () => {
  const config = devConfig(2);

  it('is its own compose project, in its own worktree', () => {
    expect(config.project).toBe('soirely-dev2');
    expect(developerOf('/Users/x/Projects/soirely-dev2')).toBe(2);
    expect(developerOf('/Users/x/Projects/soirely')).toBeNull();
    expect(developerOf('/Users/x/Projects/soirely-qa2')).toBeNull();
    expect(developerOf('/Users/x/Projects/soirely-lead')).toBeNull();
  });

  it('shares no port with development, QA or any other role', () => {
    const ports = [
      ...Object.values(qaConfig(1).ports).map((port) => port - 10000),
      ...TESTERS.flatMap((tester) => Object.values(qaConfig(tester).ports)),
      ...Object.keys(STACKS).flatMap((role) => Object.values(roleConfig(role).ports)),
    ];
    expect(new Set(ports).size).toBe(ports.length);
    expect(Math.max(...ports)).toBeLessThan(65536);
    expect(config.ports.API_PORT).toBe(48080);
  });

  it('refuses a developer it has no stack for', () => {
    expect(() => devConfig(1)).toThrow(/no developer 1/);
    expect(DEVELOPERS.every((developer) => `dev${developer}` in STACKS)).toBe(true);
  });

  it('writes the project and its ports into .env', () => {
    const example = readFileSync(new URL('../.env.example', import.meta.url), 'utf8');
    const rendered = renderDevEnv(example, config);
    expect(rendered).toMatch(/^COMPOSE_PROJECT_NAME=soirely-dev2$/m);
    expect(rendered).toMatch(/^API_PORT=48080$/m);
    expect(rendered).toMatch(/^SOIRELY_API_URL=http:\/\/127\.0\.0\.1:48080$/m);
    expect(rendered).toMatch(/^# Generated by scripts\/dev-env\.mjs/);
  });
});

describe('the other roles’ stacks', () => {
  it('each have a worktree named for the role', () => {
    expect(roleConfig('lead').project).toBe('soirely-lead');
    expect(roleOf('/Users/x/Projects/soirely-fr')).toBe('fr');
    expect(roleOf('/Users/x/Projects/soirely-qa')).toBeNull();
    expect(roleOf('/Users/x/Projects/soirely')).toBeNull();
  });

  it('refuse a role with no stack', () => {
    expect(() => roleConfig('pm')).toThrow(/no stack for pm/);
    expect(() => roleConfig('toString')).toThrow(/no stack for toString/);
  });

  it('write the role into .env', () => {
    const example = readFileSync(new URL('../.env.example', import.meta.url), 'utf8');
    const rendered = renderDevEnv(example, roleConfig('es'));
    expect(rendered).toMatch(/^COMPOSE_PROJECT_NAME=soirely-es$/m);
    expect(rendered).toMatch(/^API_PORT=33080$/m);
    expect(rendered).toMatch(/^# The es stack/m);
  });
});
