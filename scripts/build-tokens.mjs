#!/usr/bin/env node
/**
 * One source, two outputs.
 *
 * `docs/design/tokens.mjs` is the design context's own extraction, kept
 * verbatim. This writes it out as the two things the clients can actually
 * consume: CSS custom properties for the web, and a typed object for the apps.
 * The web also gets the default scheme's name, which it sets on <html>.
 *
 * It is generated rather than hand-kept because the alternative is two copies
 * of every colour. The previous build had a shape-size map that disagreed with
 * the column it was meant to describe, and the disagreement was invisible until
 * something rendered wrong — a second copy of a fact does not announce that it
 * has drifted.
 *
 * `build-tokens.test.mjs` regenerates and compares, so a stale output fails CI
 * rather than reaching a screen.
 *
 * Run: node scripts/build-tokens.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { defaultScheme, schemes, tokens } from '../docs/design/tokens.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const WEB_OUT = 'apps/web/src/tokens.css';
export const NATIVE_OUT = 'apps/mobile/src/theme/tokens.ts';
export const WEB_SCHEME_OUT = 'apps/web/src/scheme.ts';

const BANNER = 'GENERATED by scripts/build-tokens.mjs from docs/design/tokens.mjs. Do not edit.';

/** Families whose numbers are pixel lengths. */
const PX = /^(space|size|radius|hitSlop|motionRise)/;
/** Families whose numbers are milliseconds. */
const MS = /^(motion(Fast|Base|Slow|Max|Pulse)|toastLifetime)$/;
/** A type style: emitted as a CSS `font` shorthand plus its own tracking. */
const isTypeStyle = (k, v) => k.startsWith('type') && v !== null && typeof v === 'object';
/** Tables of meaning, flattened per entry rather than emitted as objects. */
const MEANING = ['marks', 'replyStates', 'seatStates'];

// Borders, marks and seats carry base colours' hexes inside them. Each hex is
// swapped in one pass, so citrus's accent, which is the base broken red, is not
// swapped twice; a hex two colours share that a scheme splits cannot be guessed.
function laidOver(colours) {
  const into = {};
  for (const [key, value] of Object.entries(tokens)) {
    if (!key.startsWith('color') || typeof value !== 'string') continue;
    (into[value.toUpperCase()] ??= new Set()).add(colours[key] ?? value);
  }
  const swap = (v) =>
    typeof v === 'string'
      ? v.replace(/#[0-9A-F]{6}\b/gi, (hex) => {
          const laid = into[hex.toUpperCase()];
          if (laid === undefined) return hex;
          if (laid.size > 1) throw new Error(`${hex} becomes ${[...laid].join(' or ')}`);
          return [...laid][0];
        })
      : v !== null && typeof v === 'object'
        ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, swap(x)]))
        : v;
  const derived = {};
  for (const [key, value] of Object.entries(tokens)) {
    if (key.startsWith('color') || value === null || typeof value === 'number') continue;
    const laid = swap(value);
    if (JSON.stringify(laid) !== JSON.stringify(value)) derived[key] = laid;
  }
  return { ...derived, ...colours };
}

export const laidSchemes = Object.fromEntries(
  Object.entries(schemes).map(([name, colours]) => [name, laidOver(colours)]),
);

function cssValue(key, value) {
  if (typeof value === 'number') {
    if (MS.test(key)) return `${value}ms`;
    if (PX.test(key)) return `${value}px`;
    return String(value);
  }
  return value;
}

/** `--typeBody: 400 14px/1.5 var(--fontFamily)` plus `--typeBodyTracking`. */
function typeStyleLines(key, style) {
  return [
    `  --${key}: ${style.weight} ${style.size}px/${style.lineHeight} var(--fontFamily);`,
    `  --${key}Tracking: ${style.letterSpacing};`,
  ];
}

// Meaning tables flatten to one variable per field, because a component
// reaches for one of them at a time: --markDoneFill, --replyHeldRing.
function meaningLines(table, entries) {
  const prefix = table === 'marks' ? 'mark' : table === 'replyStates' ? 'reply' : 'seat';
  const lines = [];
  for (const [name, entry] of Object.entries(entries)) {
    for (const [field, fieldValue] of Object.entries(entry)) {
      if (field === 'glyph' || field === 'word') continue; // content, not style: these come from the catalogue
      const upper = name[0].toUpperCase() + name.slice(1);
      const cap = field[0].toUpperCase() + field.slice(1);
      lines.push(`  --${prefix}${upper}${cap}: ${fieldValue};`);
    }
  }
  return lines;
}

function buildCss() {
  const lines = [`/* ${BANNER} */`, ':root {'];

  for (const [key, value] of Object.entries(tokens)) {
    if (key === 'elevationNative') continue; // native only; a CSS variable for it would be a lie
    if (MEANING.includes(key)) continue; // handled below, flattened
    if (isTypeStyle(key, value)) {
      lines.push(...typeStyleLines(key, value));
      continue;
    }
    if (value !== null && typeof value === 'object') continue; // nothing else nested belongs in CSS
    lines.push(`  --${key}: ${cssValue(key, value)};`);
  }

  for (const table of MEANING) lines.push(...meaningLines(table, tokens[table]));

  lines.push('}');
  const base = new Set(lines);

  // A scheme is laid over the base by <html data-scheme>, which config.json sets at boot.
  for (const [name, laid] of Object.entries(laidSchemes)) {
    lines.push('', `:root[data-scheme='${name}'] {`);
    for (const [key, value] of Object.entries(laid)) {
      if (MEANING.includes(key))
        lines.push(...meaningLines(key, value).filter((l) => !base.has(l)));
      else lines.push(`  --${key}: ${value};`);
    }
    lines.push('}');
  }

  lines.push('');
  return lines.join('\n');
}

function buildNative() {
  return [
    `// ${BANNER}`,
    '',
    `const base = ${JSON.stringify(tokens, null, 2)} as const;`,
    '',
    `export const schemes = ${JSON.stringify(laidSchemes, null, 2)} as const;`,
    '',
    'export type Scheme = keyof typeof schemes;',
    '',
    'type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };',
    '',
    'type Laid = `color${string}` | keyof (typeof schemes)[Scheme];',
    '',
    'export type Tokens = { [K in keyof typeof base]: K extends Laid ? Widen<(typeof base)[K]> : (typeof base)[K] };',
    '',
    '/** The base with a scheme laid over it; a name that is no scheme keeps the base. */',
    'export function withScheme(name: string | undefined): Tokens {',
    '  return name != null && Object.hasOwn(schemes, name) ? { ...base, ...schemes[name as Scheme] } : base;',
    '}',
    '',
    `export const defaultScheme: Scheme = '${defaultScheme}';`,
    '',
    '/** Expo writes EXPO_PUBLIC_SCHEME in at build time; unset or empty, a build draws the default. */',
    'export const tokens: Tokens = withScheme(process.env.EXPO_PUBLIC_SCHEME || defaultScheme);',
    '',
    'export default tokens;',
    '',
  ].join('\n');
}

function buildWebScheme() {
  return [`// ${BANNER}`, '', `export const defaultScheme = '${defaultScheme}';`, ''].join('\n');
}

export function outputs() {
  return {
    [WEB_OUT]: buildCss(),
    [NATIVE_OUT]: buildNative(),
    [WEB_SCHEME_OUT]: buildWebScheme(),
  };
}

/** What is on disk, or null where the file is absent. */
export function onDisk() {
  const read = (p) => {
    try {
      return readFileSync(resolve(ROOT, p), 'utf8');
    } catch {
      return null;
    }
  };
  return Object.fromEntries([WEB_OUT, NATIVE_OUT, WEB_SCHEME_OUT].map((p) => [p, read(p)]));
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  for (const [path, contents] of Object.entries(outputs())) {
    writeFileSync(resolve(ROOT, path), contents);
    console.log(`wrote ${path}`);
  }
}
