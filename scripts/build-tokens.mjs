#!/usr/bin/env node
/**
 * One source, two outputs.
 *
 * `docs/design/tokens.mjs` is the design context's own extraction, kept
 * verbatim. This writes it out as the two things the clients can actually
 * consume: CSS custom properties for the web, and a typed object for the apps.
 *
 * It is generated rather than hand-kept because the alternative is two copies
 * of every colour. The previous build had a shape-size map that disagreed with
 * the column it was meant to describe, and the disagreement was invisible until
 * something rendered wrong — a second copy of a fact does not announce that it
 * has drifted.
 *
 * `build-tokens.test.mjs` regenerates and compares, so a stale output fails CI
 * rather than reaching a screen.
 *
 * Run: node scripts/build-tokens.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { tokens } from '../docs/design/tokens.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const WEB_OUT = 'apps/web/src/tokens.css';
export const NATIVE_OUT = 'apps/mobile/src/theme/tokens.ts';

const BANNER = 'GENERATED by scripts/build-tokens.mjs from docs/design/tokens.mjs. Do not edit.';

/** Families whose numbers are pixel lengths. */
const PX = /^(space|size|radius)/;
/** Families whose numbers are milliseconds. */
const MS = /^(motion(Fast|Base|Slow)|toastLifetime)$/;
/** A type style: emitted as a CSS `font` shorthand plus its own tracking. */
const isTypeStyle = (k, v) => k.startsWith('type') && v !== null && typeof v === 'object';
/** Tables of meaning, flattened per entry rather than emitted as objects. */
const MEANING = ['marks', 'replyStates', 'seatStates'];

function cssValue(key, value) {
  if (typeof value === 'number') {
    if (MS.test(key)) return `${value}ms`;
    if (PX.test(key)) return `${value}px`;
    return String(value);
  }
  return value;
}

/** `--typeBody: 400 14px/1.5 var(--fontFamily)` plus `--typeBodyTracking`. */
function typeStyleLines(key, style) {
  const family = key === 'typeMonoTime' ? 'var(--fontFamilyMono)' : 'var(--fontFamily)';
  return [
    `  --${key}: ${style.weight} ${style.size}px/${style.lineHeight} ${family};`,
    `  --${key}Tracking: ${style.letterSpacing};`,
  ];
}

function buildCss() {
  const lines = [`/* ${BANNER} */`, ':root {'];

  for (const [key, value] of Object.entries(tokens)) {
    if (key === 'elevationNative') continue; // native only; a CSS variable for it would be a lie
    if (MEANING.includes(key)) continue; // handled below, flattened
    if (isTypeStyle(key, value)) {
      lines.push(...typeStyleLines(key, value));
      continue;
    }
    if (value !== null && typeof value === 'object') continue; // nothing else nested belongs in CSS
    lines.push(`  --${key}: ${cssValue(key, value)};`);
  }

  // Meaning tables flatten to one variable per field, because a component
  // reaches for one of them at a time: --markDoneFill, --replyHeldRing.
  for (const table of MEANING) {
    const prefix = table === 'marks' ? 'mark' : table === 'replyStates' ? 'reply' : 'seat';
    for (const [name, entry] of Object.entries(tokens[table])) {
      for (const [field, fieldValue] of Object.entries(entry)) {
        if (field === 'glyph' || field === 'word') continue; // content, not style: these come from the catalogue
        const upper = name[0].toUpperCase() + name.slice(1);
        const cap = field[0].toUpperCase() + field.slice(1);
        lines.push(`  --${prefix}${upper}${cap}: ${fieldValue};`);
      }
    }
  }

  lines.push('}', '');
  return lines.join('\n');
}

function buildNative() {
  return [
    `// ${BANNER}`,
    '',
    `export const tokens = ${JSON.stringify(tokens, null, 2)} as const;`,
    '',
    'export type Tokens = typeof tokens;',
    '',
    'export default tokens;',
    '',
  ].join('\n');
}

export function outputs() {
  return { [WEB_OUT]: buildCss(), [NATIVE_OUT]: buildNative() };
}

/** What is on disk, or null where the file is absent. */
export function onDisk() {
  const read = (p) => {
    try {
      return readFileSync(resolve(ROOT, p), 'utf8');
    } catch {
      return null;
    }
  };
  return { [WEB_OUT]: read(WEB_OUT), [NATIVE_OUT]: read(NATIVE_OUT) };
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  for (const [path, contents] of Object.entries(outputs())) {
    writeFileSync(resolve(ROOT, path), contents);
    console.log(`wrote ${path}`);
  }
}
