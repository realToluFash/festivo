/** "Nigerian Naira (NGN)", in the reader's language. */
export function currencyLabel(code: string, locale: string): string {
  const name = new Intl.DisplayNames([locale], { type: 'currency' }).of(code);

  return name == null || name === code ? code : `${name} (${code})`;
}

/** An organisation's own currency as a row shows it, including one no longer offered and none at all. */
export function heldCurrencyLabel(
  code: string,
  locale: string,
  retired: (code: string) => string,
): string {
  if (code === '') return '';

  return CURRENCY_CODES.includes(code) ? currencyLabel(code, locale) : retired(code);
}

/** Sorted by name; a held code no longer offered comes first, so a save never replaces it. */
export function currencyChoices(
  held: string,
  locale: string,
  retired: (code: string) => string,
): { code: string; name: string }[] {
  const offered = CURRENCY_CODES.map((code) => ({ code, name: currencyLabel(code, locale) })).sort(
    (a, b) => a.name.localeCompare(b.name, locale),
  );

  return held === '' || CURRENCY_CODES.includes(held)
    ? offered
    : [{ code: held, name: heldCurrencyLabel(held, locale, retired) }, ...offered];
}

/** The device's country, for a form that starts on it: the first language that names one, else its likeliest. */
export function deviceCountry(languages: readonly string[]): string | null {
  for (const tag of languages) {
    const region = safeLocale(tag)?.region;
    if (region != null && COUNTRY_CODES.includes(region)) return region;
  }

  for (const tag of languages) {
    const region = safeLocale(tag)?.maximize().region;
    if (region != null && COUNTRY_CODES.includes(region)) return region;
  }

  return null;
}

/** The phone's Region setting first (UTS #35 `rg`), then the languages' country, else none: never an assumed one. */
export function deviceRegion(region: string | null, languages: readonly string[]): string | null {
  const setting = region?.toUpperCase() ?? null;

  return setting != null && COUNTRY_CODES.includes(setting) ? setting : deviceCountry(languages);
}

function safeLocale(tag: string): Intl.Locale | null {
  try {
    return new Intl.Locale(tag);
  } catch {
    return null;
  }
}
